					'',
					$row['name'],
					$row['value'],
					$row['required'],
					0,
					$row['class'],
					'',
					$row['disabled'],
					$row['attributes']
				);
		}
	}

	/**
	 * Returns the checkbox option wrapper style.
	 *
	 * @param array $row Normalized row.
	 *
	 * @return string
	 */
	private function checkbox_option_style( $row ) {
		if ( 'inline' === $row['layout'] ) {
			return 'display:inline-block;margin-right:12px;';
		}

		return 'display:block;margin-bottom:6px;';
	}

	/**
	 * Returns the normalized checkbox input name.
	 *
	 * @param array $row Normalized row.
	 *
	 * @return string
	 */
	private function checkbox_option_name( $row ) {
		if ( empty( $row['multiple'] ) ) {
			return (string) $row['name'];
		}

		return str_ends_with( (string) $row['name'], '[]' ) ? (string) $row['name'] : (string) $row['name'] . '[]';
	}

	/**
	 * Returns whether one checkbox option is selected.
	 *
	 * @param array $row    Normalized row.
	 * @param array $option Normalized option.
	 *
	 * @return bool
	 */
	private function checkbox_option_checked( $row, $option ) {
		if ( empty( $row['multiple'] ) ) {
			return (string) $row['value'] === (string) $option['value'];
		}

		$current = is_array( $row['value'] ) ? array_map( 'strval', $row['value'] ) : array();

		return in_array( (string) $option['value'], $current, true );
	}

	/**
	 * Returns one generated checkbox option id.
	 *
	 * @param array $row    Normalized row.
	 * @param array $option Normalized option.
	 * @param int   $index  Option index.
	 *
	 * @return string
	 */
	private function checkbox_option_id( $row, $option, $index ) {
		$base = sanitize_html_class( str_replace( array( '[', ']', ' ' ), array( '-', '', '-' ), (string) $row['name'] ) );

		return $base . '-' . sanitize_html_class( (string) $option['value'] ) . '-' . absint( $index );
	}
